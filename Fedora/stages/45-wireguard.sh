#!/usr/bin/env bash
# 45-wireguard.sh -- install WireGuard and generate a keypair.
#
# It creates a keypair and a stub config. It deliberately does NOT bring a
# tunnel up or write a peer: a VPN config with somebody else's endpoint in it is
# not something a hardening script should invent for you.
set -Eeuo pipefail

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd -P)"
# shellcheck source=lib/common.sh
source "$SCRIPT_DIR/lib/common.sh"
# shellcheck source=lib/state.sh
source "$SCRIPT_DIR/lib/state.sh"

IFACE="${TKOC_WG_IFACE:-wg0}"
WG_DIR="${TKOC_TEST_ROOT:-}/etc/wireguard"
WG_PORT="${TKOC_WG_PORT:-51820}"

usage() {
  cat <<'HELP'
45-wireguard -- install WireGuard and generate this machine's keypair

Usage:
  bash stages/45-wireguard.sh [--iface wg0] [--port 51820] [--dry-run]
  tkoc install wireguard
  tkoc wg show

Installs wireguard-tools, generates /etc/wireguard/<iface>.key (0600, root) and
its public key, and writes a stub /etc/wireguard/<iface>.conf with no peers.

It does not start a tunnel. Add your peer to the stub, then:
  sudo systemctl enable --now wg-quick@<iface>

Inbound UDP for WireGuard is closed by the firewall unless you ask for it:
  tkoc firewall strong --wireguard
HELP
}

while [[ $# -gt 0 ]]; do
  case "$1" in
    --iface) [[ $# -ge 2 ]] || die "--iface requires a name"; IFACE="$2"; shift 2 ;;
    --iface=*) IFACE="${1#*=}"; shift ;;
    --port) [[ $# -ge 2 ]] || die "--port requires a port number"; WG_PORT="$2"; shift 2 ;;
    --port=*) WG_PORT="${1#*=}"; shift ;;
    help|--help|-h) usage; exit 0 ;;
    *) tkoc_parse_safety_flag "$1" || die "45-wireguard: unknown option: $1"; shift ;;
  esac
done

tkoc_valid_interface "$IFACE" || die "not a valid interface name: $IFACE"
[[ "$WG_PORT" =~ ^[0-9]+$ ]] && (( WG_PORT >= 1 && WG_PORT <= 65535 )) \
  || die "--port must be a port number"

need_supported_fedora
log "WireGuard ($IFACE on UDP/$WG_PORT)"

rpm_installed wireguard-tools || dnf_install wireguard-tools

KEY="$WG_DIR/$IFACE.key"
PUB="$WG_DIR/$IFACE.pubkey"
CONF="$WG_DIR/$IFACE.conf"

if [[ -f "$KEY" ]]; then
  log "keypair already exists: $KEY"
else
  if tkoc_bool_enabled TKOC_DRY_RUN disabled; then
    log "[dry-run] would generate a keypair at $KEY"
  else
    command -v wg >/dev/null 2>&1 || die "wg is unavailable after install"
    run_root mkdir -p -- "$WG_DIR"
    run_root chmod 700 "$WG_DIR"
    # umask, not a chmod afterwards: the private key must never exist,
    # even momentarily, with a mode that lets another account read it.
    ( umask 077; wg genkey | run_root tee "$KEY" >/dev/null )
    run_root chmod 600 "$KEY"
    run_root sh -c "wg pubkey < '$KEY' > '$PUB'"
    run_root chmod 644 "$PUB"
    log "generated $KEY"
  fi
fi

if [[ -f "$CONF" ]]; then
  log "config already exists: $CONF (left alone)"
else
  if tkoc_bool_enabled TKOC_DRY_RUN disabled; then
    log "[dry-run] would write a peerless stub config at $CONF"
  else
    tmp="$(mktemp "${TMPDIR:-/tmp}/tkoc-wg.XXXXXX")"
    cat > "$tmp" <<STUB
# Generated by tkoc. Add your peer below, then:
#   sudo systemctl enable --now wg-quick@$IFACE
#
# This file has no peers on purpose. Nothing here connects anywhere until you
# put a real endpoint in it.
[Interface]
PrivateKey = $(run_root cat "$KEY" 2>/dev/null || printf '<run: sudo cat %s>' "$KEY")
# Address = 10.0.0.2/32
ListenPort = $WG_PORT

# [Peer]
# PublicKey = <the peer's public key>
# Endpoint = <host>:<port>
# AllowedIPs = 0.0.0.0/0
# PersistentKeepalive = 25
STUB
    run_root install -m 0600 -- "$tmp" "$CONF"
    rm -f -- "$tmp"
    log "wrote stub config $CONF"
  fi
fi

printf '\n'
[[ -f "$PUB" ]] && log "public key: $(cat "$PUB" 2>/dev/null || printf '(needs privilege to read)')"
log "no tunnel was started. Add a peer to $CONF, then:"
log "  sudo systemctl enable --now wg-quick@$IFACE"
log "to accept inbound WireGuard, re-apply a tier with --wireguard"
